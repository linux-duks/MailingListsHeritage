#!/usr/bin/env python3
"""
Generate a git mailmap file from email fixtures.

Scans .eml files for (name, email) pairs in From, To, Cc headers
and Signed-off-by, Reviewed-by, Tested-by, Acked-by trailer lines.
Groups identities by normalized name and writes a .mailmap file
with the most-complete form as canonical.

Usage:
    python3 generate_mailmap.py --input-dir DIR --output FILE
    python3 generate_mailmap.py -i DIR -o FILE
"""

import argparse
import email.policy
import email.parser
import email.utils as email_utils
import os
import re
import sys
from collections import defaultdict


RE_TRAILER = re.compile(
    r"^(Signed-off-by|Reviewed-by|Tested-by|Acked-by|Reported-by"
    r"|Suggested-by|Co-developed-by|Fixes|Cc):\s*(.+)$",
    re.IGNORECASE,
)
RE_ADDRESS = re.compile(r"^\s*([^<]*?)\s*<?([^>@\s]+@[^>\s]+)>?\s*$")
RE_RFC2047 = re.compile(r"=\?[^?]+\?[bqBQ]\?[^?]*\?=")


def extract_addresses_from_file(filepath: str) -> list[tuple[str, str]]:
    """Extract (name, email) pairs from an .eml file."""
    results = []
    with open(filepath, "r", errors="replace") as fh:
        content = fh.read()

    msg = email.parser.Parser(policy=email.policy.compat32).parsestr(content)

    for header in ("From", "To", "Cc"):
        for addr in email_utils.getaddresses(msg.get_all(header, [])):
            name, mail = addr
            if mail and "@" in mail:
                name = name.strip()
                if not RE_RFC2047.search(name):
                    results.append((name, mail.strip().lower()))

    body = ""
    if msg.is_multipart():
        for part in msg.walk():
            if part.get_content_type() == "text/plain":
                payload = part.get_payload(decode=True)
                if payload:
                    body += payload.decode("utf-8", errors="replace")
    else:
        payload = msg.get_payload(decode=True)
        if payload:
            body = payload.decode("utf-8", errors="replace")

    for line in body.splitlines():
        m = RE_TRAILER.match(line.strip())
        if m:
            raw = m.group(2).strip()
            raw = raw.replace("(a)", "@").replace("(A)", "@")
            addr = RE_ADDRESS.match(raw)
            if addr:
                name = addr.group(1).strip() if addr.group(1) else ""
                email_addr = addr.group(2).strip().lower()
                results.append((name, email_addr))
            elif "@" in raw:
                results.append(("", raw.strip().lower()))

    return results


def normalize_name(name: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", "", name.lower())).strip()


def build_mailmap_entries(
    addresses: list[tuple[str, str]],
) -> list[tuple[str, str, str]]:
    groups: dict[str, set[tuple[str, str]]] = defaultdict(set)
    for name, email_addr in addresses:
        key = normalize_name(name) if name else None
        if key is None:
            continue  # skip email-only entries for grouping
        groups[key].add((name, email_addr))

    entries = []
    for addr_set in groups.values():
        if len(addr_set) < 2:
            continue

        names_list = list(addr_set)
        best = max(
            names_list,
            key=lambda x: (
                1 if "." in x[1].split("@")[0] else 0,
                len(x[0]) if x[0] else 0,
            ),
        )
        canonical_name = best[0]
        canonical_email = best[1]

        for name, email_addr in names_list:
            if email_addr == canonical_email:
                continue
            entries.append((canonical_name, canonical_email, email_addr))

    return entries


def write_mailmap(
    entries: list[tuple[str, str, str]], output_path: str
) -> None:
    with open(output_path, "w") as fh:
        fh.write("# Generated by generate_mailmap.py\n")
        fh.write("# Format: Canonical Name <canonical@email> <alias@email>\n\n")

        # Deduplicate
        seen = set()
        for canonical_name, canonical_email, alias_email in sorted(
            entries,
            key=lambda x: (x[0].lower(), x[1]),
        ):
            key = (canonical_name, canonical_email, alias_email)
            if key in seen:
                continue
            seen.add(key)
            fh.write(
                f"{canonical_name} <{canonical_email}> <{alias_email}>\n"
            )


def main():
    parser = argparse.ArgumentParser(
        description="Generate a git mailmap from email fixtures"
    )
    parser.add_argument(
        "-i", "--input-dir", required=True, help="Directory containing .eml files"
    )
    parser.add_argument("-o", "--output", required=True, help="Output .mailmap file")
    args = parser.parse_args()

    input_dir = args.input_dir
    if not os.path.isdir(input_dir):
        print(f"Error: input directory not found: {input_dir}", file=sys.stderr)
        sys.exit(1)

    all_addresses = []
    for root, _dirs, files in os.walk(input_dir):
        for fname in sorted(files):
            if fname.endswith(".eml"):
                fpath = os.path.join(root, fname)
                addrs = extract_addresses_from_file(fpath)
                all_addresses.extend(addrs)

    unique = list(set(all_addresses))
    entries = build_mailmap_entries(unique)
    write_mailmap(entries, args.output)

    print(f"Wrote {len(entries)} entries to {args.output}")


if __name__ == "__main__":
    main()
